// 为每个节点 id 生成独有收束句
function makeUniqueTail(dom, id, n, k) {
  // 基于关键词生成
  const kw = k[0] || n;
  if (dom === "economics") {
    return `在经济政策与市场实践中，${n}的运行条件、约束边界与福利效应是福利分析与政策评估的重要切入点。`;
  }
  if (dom === "market") {
    return `在电力市场设计中，${n}的报价方式、结算周期与责任分配直接影响市场主体的参与激励与系统运行绩效。`;
  }
  if (dom === "law") {
    return `在司法适用中，${n}的构成要件、举证责任分配与抗辩事由是裁判文书说理的核心，其类案累积推动规则细化。`;
  }
  if (dom === "sociology") {
    return `在经验研究中，${n}的测量通常结合定性与定量方法，其历史变迁与跨文化比较是社会学理论建构的重要素材。`;
  }
  if (dom === "medicine") {
    return `在临床实践中，${n}的适应证、禁忌证与疗效评价需结合循证证据与患者个体化因素综合判断。`;
  }
  return "";
}

for (const dom of ["economics", "market", "law", "sociology", "medicine"]) {
  const f = path.join(ROOT, "assets/data/text", dom + ".js");
  const sb = { window: {} };
  new Function("window", fs.readFileSync(f, "utf8"))(sb.window);
  const texts = sb.window.KG_TEXT[dom];
  // 节点名映射
  const sb2 = { window: {} };
  new Function("window", fs.readFileSync(path.join(ROOT, "assets/data/domains", dom + ".js"), "utf8"))(sb2.window);
  const nodeMap = {};
  for (const n of sb2.window.KG.nodes) nodeMap[n.id] = n;

  let rewritten = 0;
  for (const [id, orig] of Object.entries(texts)) {
    let v = orig;
    // 检查结尾是否有重复尾句
    let found = false;
    for (const tail of repetitiveTails) {
      if (v.endsWith(tail)) {
        v = v.slice(0, v.length - tail.length);
        found = true;
        break;
      }
    }
    if (found) {
      const node = nodeMap[id] || { n: id, k: [] };
      const newTail = makeUniqueTail(dom, id, node.n || id, node.k || []);
      v = v.replace(/\s+$/, "") + newTail;
      texts[id] = v;
      rewritten++;
    }
  }
  console.log(dom + ": rewritten " + rewritten + " entries");

  // 重写文件
  let src = fs.readFileSync(f, "utf8");
  const marker = "/* ===== 加厚文本 ===== */";
  const idx = src.indexOf(marker);
  const head = src.slice(0, idx);
  let block = "window.KG_TEXT[" + JSON.stringify(dom) + "] = ";
  block += JSON.stringify(texts, null, 2);
  block += ";\n";
  fs.writeFileSync(f, head + marker + "\n" + block, "utf8");
}
